import Foundation

// The conversion matrix: what every operation was really checked against, written as Markdown by `./build.sh conformance` (docs/conversion-matrix.md).
// The generated conformance tests report each case here (operation, input -> output kinds, what the oracle measured, pass / fail / skip); `render` joins that with the
// registry (which oracle claims the operation and what it proves, which operations are exempt and why) so the document also lists what was NOT run on this Mac.
// Nothing here runs unless SC_CONFORMANCE_MATRIX=<file> is set.

@MainActor
enum ConformanceMatrix {
    enum Outcome: Equatable {
        case passed
        case failed(String)
        case skipped(String)
    }

    struct Row: Equatable {
        var operationID: String
        var caseLabel: String
        var inputs: [String]
        var outputs: [String]
        var notes: [String]
        var outcome: Outcome
    }

    private(set) static var rows: [Row] = []

    static var outputPath: String? {
        let v = ProcessInfo.processInfo.environment["SC_CONFORMANCE_MATRIX"]
        return (v?.isEmpty ?? true) ? nil : v
    }

    static func record(_ row: Row) { rows.append(row) }

    /// A skip or a failure that happened before any case ran (exempt, a tool missing, an oracle with no fixtures, a failing fixture).
    static func record(operationID: String, outcome: Outcome) {
        rows.append(Row(operationID: operationID, caseLabel: "", inputs: [], outputs: [], notes: [], outcome: outcome))
    }

    /// Called once when the self-test run is over; writes the file when SC_CONFORMANCE_MATRIX is set and at least one conformance case reported.
    static func writeIfRequested() {
        guard let path = outputPath, !rows.isEmpty else { return }
        let text = render(registry: ConformanceRegistry.shared, operations: OperationRegistry.shared.allOperations())
        do {
            try FileManager.default.createDirectory(at: URL(fileURLWithPath: path).deletingLastPathComponent(), withIntermediateDirectories: true)
            try text.write(toFile: path, atomically: true, encoding: .utf8)
            out("conversion matrix written: \(path)")
        } catch {
            out("conversion matrix NOT written (\(path)): \(error.localizedDescription)")
        }
    }

    // MARK: Rendering

    static func render(registry: ConformanceRegistry, operations: [Operation], rows: [Row]? = nil) -> String {
        let ops = operations.sorted { ($0.meta.family.rawValue, $0.meta.id) < ($1.meta.family.rawValue, $1.meta.id) }
        // The harness's own self-tests run fake operations through the runner on purpose (to prove a fake conversion is caught): those are not part of the app.
        let known = Set(ops.map(\.meta.id))
        let rows = (rows ?? Self.rows).filter { known.contains($0.operationID) }
        let byOperation = Dictionary(grouping: rows, by: \.operationID)

        var passed = 0, failed = 0, skipped = 0
        for r in rows {
            switch r.outcome {
            case .passed: passed += 1
            case .failed: failed += 1
            case .skipped: skipped += 1
            }
        }
        var exempt = 0, covered = 0
        for op in ops { if registry.exemption(for: op.meta) != nil { exempt += 1 } else if registry.coveringOracle(for: op.meta) != nil { covered += 1 } }

        var md = "# Conversion matrix\n\n"
        md += "Generated by `./build.sh conformance`. Every operation of the app is run on a real generated file and judged by an independent reader, never by the code that wrote the result.\n"
        md += "A conversion that only renamed or copied a file fails the generic checks (the real format is sniffed from the bytes, the result must decode, differ from the input and keep its content).\n\n"
        md += "| | |\n|---|---|\n"
        md += "| Operations | \(ops.count) |\n| Judged by a content oracle | \(covered) |\n| Exempt (with a reason) | \(exempt) |\n"
        md += "| Cases passed | \(passed) |\n| Cases failed | \(failed) |\n| Cases skipped on this Mac | \(skipped) |\n\n"
        if failed > 0 { md += "**\(failed) case(s) failed in this run; see the Result column.**\n\n" }

        md += "## How each kind of result is judged\n\n| Oracle | What it proves | Operations |\n|---|---|---|\n"
        var byOracle: [String: [String]] = [:]
        for op in ops where registry.exemption(for: op.meta) == nil {
            if let o = registry.coveringOracle(for: op.meta) { byOracle[o.id, default: []].append(op.id) }
        }
        for (id, list) in byOracle.sorted(by: { $0.key < $1.key }) {
            let proves = registry.allOracles.first { $0.id == id }?.proves ?? ""
            md += "| `\(id)` | \(cell(proves)) | \(list.count) |\n"
        }
        md += "\n"

        var family = ""
        for op in ops {
            if op.meta.family.rawValue != family {
                family = op.meta.family.rawValue
                md += "## \(family)\n\n| Operation | Case | Input → output | Measured | Result |\n|---|---|---|---|---|\n"
            }
            let name = "`\(op.meta.id)`"
            if let reason = registry.exemption(for: op.meta) {
                md += "| \(name) | | | | Exempt: \(cell(reason)) |\n"
                continue
            }
            guard let list = byOperation[op.meta.id], !list.isEmpty else {
                let missing = op.meta.requires.filter { !ToolLocator.shared.has($0) }.map(\.rawValue)
                md += "| \(name) | | | | Not run on this Mac\(missing.isEmpty ? "" : " (needs " + missing.joined(separator: ", ") + ")") |\n"
                continue
            }
            for r in list {
                let io = r.inputs.isEmpty && r.outputs.isEmpty ? "" : "\(kinds(r.inputs)) → \(kinds(r.outputs))"
                let result: String
                switch r.outcome {
                case .passed: result = "Passed"
                case .failed(let m): result = "**FAILED**: \(cell(String(m.prefix(300))))"
                case .skipped(let why): result = "Skipped: \(cell(String(why.prefix(200))))"
                }
                md += "| \(name) | \(cell(r.caseLabel)) | \(cell(io)) | \(cell(r.notes.joined(separator: "; "))) | \(result) |\n"
            }
        }
        md += "\n"
        return md
    }

    /// "pdf" or "jpg ×3" for a list of file extensions.
    private static func kinds(_ exts: [String]) -> String {
        var order: [String] = [], count: [String: Int] = [:]
        for e in exts { if count[e] == nil { order.append(e) }; count[e, default: 0] += 1 }
        return order.map { count[$0]! > 1 ? "\($0) ×\(count[$0]!)" : $0 }.joined(separator: ", ")
    }

    /// One table cell: no line breaks, no raw pipes.
    private static func cell(_ s: String) -> String {
        s.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "|", with: "\\|").trimmingCharacters(in: .whitespaces)
    }
}
